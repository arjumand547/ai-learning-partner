const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const NotesExport = require('../js/export.js');
const rtf = NotesExport.toRtf('# Main idea\n\n- **Important** item\n1. First step\nCode: `x = 1`\nUse {braces} and \\ slash: café.');
assert(rtf.startsWith('{\\rtf1\\ansi'), 'creates an RTF document Word can open');
assert(rtf.includes('\\b\\fs28 Main idea\\b0\\fs22\\par'), 'exports markdown headings');
assert(rtf.includes('\\bullet\\tab \\b Important\\b0 item\\par'), 'exports bold list items');
assert(rtf.includes('\\tab First step\\par'), 'exports ordered list items');
assert(rtf.includes('\\f1 x = 1\\f0'), 'exports inline code');
assert(rtf.includes('\\{braces\\} and \\\\ slash:'), 'escapes RTF control characters');
assert(rtf.includes('caf\\u233?'), 'encodes unicode safely');
const context = vm.createContext({ localStorage: { removeItem() {} } });
vm.runInContext(fs.readFileSync(require.resolve('../js/store.js'), 'utf8'), context);
vm.runInContext(fs.readFileSync(require.resolve('../js/ui.js'), 'utf8'), context);
const answer = '## Steps\n\n- **First** item\n- Second item\n\n```js\nalert(1)\n```\n<img src=x>';
const html = vm.runInContext(`md(${JSON.stringify(answer)})`, context);
assert(html.includes('<h3>Steps</h3>'), 'renders markdown headings');
assert(html.includes('<ul><li><strong>First</strong> item</li><li>Second item</li></ul>'), 'renders semantic lists');
assert(html.includes('<pre><code>alert(1)\n</code></pre>'), 'renders code blocks');
assert(html.includes('&lt;img src=x&gt;'), 'escapes HTML in AI replies');
console.log('answer export tests passed');
